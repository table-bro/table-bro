/**
 * The color mode of a table: light or dark.
 * @group Configuration
 */
export declare type BroTheme = 'light' | 'dark';

/**
 * The theme that the application sets: light, dark, or auto, which follows the color scheme of the system.
 * @group Configuration
 */
export declare type BroUserTheme = BroTheme | 'auto';
